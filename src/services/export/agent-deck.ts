/**
 * Full executive deck for the strategic-advisor experience ("Download slides").
 * Builds a structured, editable PPTX from the agent's grounded state: cover
 * (the recommendation), one-pager snapshot, native charts, talking points,
 * deal pipeline vs risks, scenarios/watchlist, sources. Bilingual EN/AR.
 */
import { humanizeValue } from "@/services/agent/format";
import {
  CONTENT_W,
  FONT,
  MARGIN,
  P,
  PAGE_W,
  defineBaseMaster,
  slideHeading,
  statBox,
} from "@/services/export/pptx-kit";
import PptxGenJS from "pptxgenjs";

export interface AgentDeckPayload {
  locale?: "en" | "ar";
  classification: string;
  countryName: string;
  iso3: string;
  sector?: string;
  audience?: string;
  title: string;
  bluf: string;
  whyNow?: string;
  heroMetric?: { label: string; value: string; delta?: string };
  confidence?: string;
  talkingPoints: string[];
  deals: { title: string; score: number; horizon?: string }[];
  risks: { text: string; likelihood?: string }[];
  scenarios: { name: string; outlook: string; likelihood?: string }[];
  watchlist: string[];
  indicators: {
    code: string;
    label: string;
    value: number;
    unit: string;
    year: number;
    source: string;
  }[];
  gdpSeries: { year: number; value: number }[];
  forecast?: { next: number; lower: number; upper: number };
  trade?: {
    totalUsd: number;
    exportsUsd: number;
    importsUsd: number;
    source: string;
    year: number;
  };
}

const L = {
  numbers: { en: "The numbers behind the recommendation", ar: "الأرقام خلف التوصية" },
  gdpTrend: { en: "GDP trend — US$ billions", ar: "اتجاه الناتج المحلي — مليار دولار" },
  forecastSeries: { en: "Forecast", ar: "التوقع" },
  renewShare: { en: "Renewables share of energy", ar: "حصة الطاقة المتجددة" },
  other: { en: "Other sources", ar: "مصادر أخرى" },
  renewables: { en: "Renewables", ar: "متجددة" },
  tradeMix: { en: "Trade with UAE — composition", ar: "التجارة مع الإمارات — التركيبة" },
  exportsL: { en: "UAE exports", ar: "صادرات الإمارات" },
  importsL: { en: "UAE imports", ar: "واردات الإمارات" },
  talking: { en: "Talking points — the ask", ar: "نقاط الحديث — المطلب" },
  oppRisk: {
    en: "Opportunities outweigh the risks — if managed",
    ar: "الفرص تفوق المخاطر — إذا أُديرت",
  },
  deals: { en: "Deal pipeline", ar: "مسار الصفقات" },
  risks: { en: "Risks & sensitivities", ar: "المخاطر والحساسيات" },
  scenarios: { en: "Scenarios & what to watch", ar: "السيناريوهات وما يجب مراقبته" },
  scenCol: { en: "Scenarios", ar: "السيناريوهات" },
  watchCol: { en: "What to watch", ar: "ما يجب مراقبته" },
  sources: { en: "Every figure is cited", ar: "كل رقم موثّق" },
  confidence: { en: "Analytic confidence", ar: "الثقة التحليلية" },
  confSrc: { en: "ICD-203 confidence levels", ar: "مستويات الثقة ICD-203" },
  preparedFor: { en: "Prepared for", ar: "أُعدّت لـ" },
  attribution: {
    en: "Generated by the Country Intelligence Platform — classification-gated AI, full audit trail, figures validated against source data.",
    ar: "أُعدّت بواسطة منصة الذكاء القُطري — ذكاء اصطناعي مقيّد بالتصنيف، وسجل تدقيق كامل، وأرقام مُتحقق منها مقابل المصادر.",
  },
} as const;

export async function renderAgentDeckPptx(
  deck: AgentDeckPayload,
  onePagerPng: string | null,
): Promise<Buffer> {
  const loc = deck.locale === "ar" ? "ar" : "en";
  const rtl = loc === "ar";
  const t = (k: keyof typeof L) => L[k][loc];
  const created = new Date().toISOString().slice(0, 10);

  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_WIDE";
  pptx.title = deck.title;
  defineBaseMaster(pptx, deck.classification, `Country Intelligence Platform · ${created}`);

  const byCode = new Map(deck.indicators.map((i) => [i.code, i]));
  const gdp = byCode.get("gdp");
  const growth = byCode.get("gdp_growth");
  const population = byCode.get("population");
  const renew = byCode.get("renew_share");
  const electricity = byCode.get("electricity_pc");
  const fdi = byCode.get("fdi");

  // ── 1 · Cover — the recommendation up front ──
  const cover = pptx.addSlide({ masterName: "BASE" });
  cover.addShape("rect", { x: 0, y: 0.46, w: PAGE_W, h: 0.025, fill: { color: P.gold } });
  cover.addShape("rect", {
    x: rtl ? PAGE_W - MARGIN - 0.1 : MARGIN,
    y: 1.5,
    w: 0.1,
    h: 2.7,
    fill: { color: P.gold },
  });
  const coverX = rtl ? MARGIN : 0.92;
  const align = rtl ? ("right" as const) : ("left" as const);
  cover.addText(`${deck.countryName} (${deck.iso3})${deck.sector ? ` · ${deck.sector}` : ""}`, {
    x: coverX,
    y: 1.5,
    w: 10,
    h: 0.4,
    fontSize: 14,
    color: P.goldDeep,
    bold: true,
    charSpacing: rtl ? 0 : 2,
    fontFace: FONT,
    align,
  });
  cover.addText(deck.bluf, {
    x: coverX,
    y: 1.95,
    w: 10.1,
    h: 1.9,
    fontSize: 27,
    bold: true,
    color: P.ink,
    fontFace: FONT,
    valign: "top",
    align,
  });
  cover.addText(
    `${deck.audience ? `${t("preparedFor")} ${deck.audience} · ` : ""}${created}${deck.confidence ? ` · ${deck.confidence.toUpperCase()}` : ""}`,
    { x: coverX, y: 3.95, w: 10, h: 0.4, fontSize: 13, color: P.dim, fontFace: FONT, align },
  );
  const coverStats = [
    gdp && { label: loc === "ar" ? "حجم السوق (الناتج)" : "Market size (GDP)", i: gdp },
    growth && { label: loc === "ar" ? "النمو" : "GDP growth", i: growth },
    population && { label: loc === "ar" ? "السكان" : "Population", i: population },
  ].filter((x): x is NonNullable<typeof x> => Boolean(x));
  coverStats.forEach((st, idx) => {
    statBox(
      cover,
      MARGIN + idx * 4.13,
      5.05,
      3.93,
      1.35,
      st.label,
      humanizeValue(st.i.value, st.i.unit),
      `${st.i.source} · ${st.i.year}`,
      rtl,
    );
  });

  // ── 2 · One-pager snapshot (leave-behind) ──
  if (onePagerPng) {
    const snap = pptx.addSlide({ masterName: "BASE" });
    snap.addImage({ data: onePagerPng, x: 0.35, y: 0.42, w: 12.63, h: 6.9 });
  }

  // ── 3 · The numbers — native, editable charts ──
  const hasCharts = deck.gdpSeries.length > 1 || deck.trade || renew;
  if (hasCharts) {
    const nums = pptx.addSlide({ masterName: "BASE" });
    slideHeading(nums, t("numbers"), rtl);
    if (deck.gdpSeries.length > 1) {
      const labels = deck.gdpSeries.map((pt) => String(pt.year));
      const values = deck.gdpSeries.map((pt) => Math.round(pt.value / 1e9));
      const seriesDefs = [{ name: t("gdpTrend"), labels, values }];
      if (deck.forecast) {
        const lastYear = deck.gdpSeries[deck.gdpSeries.length - 1]?.year ?? 0;
        seriesDefs.push({
          name: t("forecastSeries"),
          labels: [...labels, String(lastYear + 1)],
          values: [
            ...values.slice(0, -1).map(() => null as unknown as number),
            values[values.length - 1] as number,
            Math.round(deck.forecast.next / 1e9),
          ],
        });
      }
      nums.addChart(pptx.ChartType.line, seriesDefs, {
        x: MARGIN,
        y: 1.6,
        w: 7.4,
        h: 4.5,
        chartColors: [P.gold, P.goldDeep],
        lineSize: 3,
        lineSmooth: true,
        lineDataSymbol: "circle",
        lineDataSymbolSize: 6,
        showTitle: true,
        title: t("gdpTrend"),
        titleFontSize: 12,
        titleColor: P.dim,
        catAxisLabelColor: P.dim,
        valAxisLabelColor: P.dim,
        catAxisLabelFontSize: 10,
        valAxisLabelFontSize: 10,
        valGridLine: { color: P.line, style: "solid", size: 1 },
        plotArea: { fill: { color: P.card } },
        showLegend: Boolean(deck.forecast),
        legendPos: "b",
        legendFontSize: 9,
      });
    }
    if (deck.trade && deck.trade.totalUsd > 0) {
      const exPct = Math.round((deck.trade.exportsUsd / deck.trade.totalUsd) * 100);
      nums.addChart(
        pptx.ChartType.doughnut,
        [
          {
            name: t("tradeMix"),
            labels: [t("exportsL"), t("importsL")],
            values: [exPct, 100 - exPct],
          },
        ],
        {
          x: 8.35,
          y: 1.6,
          w: 4.35,
          h: 2.5,
          chartColors: [P.gold, P.line],
          holeSize: 62,
          showTitle: true,
          title: `${t("tradeMix")} — ${humanizeValue(deck.trade.totalUsd, "USD")}`,
          titleFontSize: 11,
          titleColor: P.dim,
          showLegend: true,
          legendPos: "b",
          legendFontSize: 9,
          showValue: false,
        },
      );
    }
    const railY = deck.trade ? 4.35 : 1.6;
    const railStats = [
      renew && { label: t("renewShare"), i: renew },
      electricity && {
        label: loc === "ar" ? "استهلاك الكهرباء للفرد" : "Electricity use / capita",
        i: electricity,
      },
      fdi && { label: loc === "ar" ? "الاستثمار الأجنبي" : "FDI inflows", i: fdi },
    ]
      .filter((x): x is NonNullable<typeof x> => Boolean(x))
      .slice(0, deck.trade ? 1 : 3);
    railStats.forEach((st, idx) => {
      statBox(
        nums,
        8.35,
        railY + idx * 1.6,
        4.35,
        1.4,
        st.label,
        humanizeValue(st.i.value, st.i.unit),
        `${st.i.source} · ${st.i.year}`,
        rtl,
      );
    });
  }

  // ── 4 · Talking points — the ask ──
  if (deck.talkingPoints.length > 0) {
    const s = pptx.addSlide({ masterName: "BASE" });
    slideHeading(s, t("talking"), rtl);
    s.addText(
      deck.talkingPoints.slice(0, 5).map((tp) => ({
        text: tp,
        options: { bullet: { type: "number", color: P.gold, style: "arabicPeriod" } },
      })),
      {
        x: MARGIN,
        y: 1.6,
        w: CONTENT_W,
        h: 4.9,
        fontSize: 17,
        color: P.ink,
        fontFace: FONT,
        paraSpaceAfter: 14,
        lineSpacingMultiple: 1.15,
        valign: "top",
        align,
        rtlMode: rtl,
      },
    );
  }

  // ── 5 · Deal pipeline ⇄ risks — split comparison ──
  const deals = deck.deals.slice(0, 4);
  const risks = deck.risks.slice(0, 4);
  if (deals.length > 0 || risks.length > 0) {
    const s = pptx.addSlide({ masterName: "BASE" });
    slideHeading(s, t("oppRisk"), rtl);
    const col = (x: number, header: string, color: string, items: string[]): void => {
      s.addShape("roundRect", {
        x,
        y: 1.6,
        w: 5.96,
        h: 4.9,
        rectRadius: 0.08,
        fill: { color: P.card },
        line: { color: P.line, width: 1 },
      });
      s.addShape("rect", { x, y: 1.6, w: 5.96, h: 0.06, fill: { color } });
      s.addText(header.toUpperCase(), {
        x: x + 0.25,
        y: 1.8,
        w: 5.4,
        h: 0.35,
        fontSize: 12,
        bold: true,
        color,
        charSpacing: rtl ? 0 : 1.5,
        fontFace: FONT,
        align,
      });
      s.addText(
        items.map((txt) => ({ text: txt, options: { bullet: { code: "25CF", color } } })),
        {
          x: x + 0.25,
          y: 2.3,
          w: 5.45,
          h: 4.0,
          fontSize: 13,
          color: P.ink,
          fontFace: FONT,
          paraSpaceAfter: 10,
          valign: "top",
          align,
          rtlMode: rtl,
        },
      );
    };
    const dealLines = deals.map((d) => `${d.title} — ${Math.round(d.score)}/100`);
    const riskLines = risks.map((r) =>
      r.likelihood ? `${r.text} (${r.likelihood.replace(/_/g, " ")})` : r.text,
    );
    if (deals.length > 0) col(MARGIN, t("deals"), P.ok, dealLines);
    if (risks.length > 0)
      col(deals.length > 0 ? MARGIN + 6.17 : MARGIN, t("risks"), P.risk, riskLines);
  }

  // ── 6 · Scenarios & watchlist ──
  const scenarios = deck.scenarios.slice(0, 3);
  const watchlist = deck.watchlist.slice(0, 5);
  if (scenarios.length > 0 || watchlist.length > 0) {
    const s = pptx.addSlide({ masterName: "BASE" });
    slideHeading(s, t("scenarios"), rtl);
    const half = (CONTENT_W - 0.4) / 2;
    if (scenarios.length > 0) {
      s.addText(t("scenCol").toUpperCase(), {
        x: MARGIN,
        y: 1.6,
        w: half,
        h: 0.35,
        fontSize: 12,
        bold: true,
        color: P.goldDeep,
        charSpacing: rtl ? 0 : 1.5,
        fontFace: FONT,
        align,
      });
      s.addText(
        scenarios.map((sc) => ({
          text: `${sc.name}: ${sc.outlook}${sc.likelihood ? ` (${sc.likelihood.replace(/_/g, " ")})` : ""}`,
          options: { bullet: { code: "25CF", color: P.gold } },
        })),
        {
          x: MARGIN,
          y: 2.1,
          w: half,
          h: 4.2,
          fontSize: 13,
          color: P.ink,
          fontFace: FONT,
          paraSpaceAfter: 12,
          valign: "top",
          align,
          rtlMode: rtl,
        },
      );
    }
    if (watchlist.length > 0) {
      const x = scenarios.length > 0 ? MARGIN + half + 0.4 : MARGIN;
      s.addText(t("watchCol").toUpperCase(), {
        x,
        y: 1.6,
        w: half,
        h: 0.35,
        fontSize: 12,
        bold: true,
        color: P.amber,
        charSpacing: rtl ? 0 : 1.5,
        fontFace: FONT,
        align,
      });
      s.addText(
        watchlist.map((wi) => ({
          text: wi,
          options: { bullet: { code: "25CF", color: P.amber } },
        })),
        {
          x,
          y: 2.1,
          w: half,
          h: 4.2,
          fontSize: 13,
          color: P.ink,
          fontFace: FONT,
          paraSpaceAfter: 12,
          valign: "top",
          align,
          rtlMode: rtl,
        },
      );
    }
  }

  // ── 7 · Sources & confidence ──
  const sources = [
    ...new Set([
      ...deck.indicators.map((i) => `${i.source} · ${i.year}`),
      ...(deck.trade ? [`${deck.trade.source} · ${deck.trade.year}`] : []),
    ]),
  ].slice(0, 10);
  const last = pptx.addSlide({ masterName: "BASE" });
  slideHeading(last, t("sources"), rtl);
  last.addText(
    (sources.length > 0 ? sources : ["—"]).map((txt) => ({
      text: txt,
      options: { bullet: { code: "25CF", color: P.gold } },
    })),
    {
      x: MARGIN,
      y: 1.6,
      w: 7.6,
      h: 4.6,
      fontSize: 13,
      color: P.ink,
      fontFace: FONT,
      paraSpaceAfter: 8,
      valign: "top",
      align,
      rtlMode: rtl,
    },
  );
  statBox(
    last,
    8.5,
    1.6,
    4.23,
    1.4,
    t("confidence"),
    (deck.confidence ?? "med").toUpperCase(),
    t("confSrc"),
    rtl,
  );
  last.addText(t("attribution"), {
    x: 8.5,
    y: 3.2,
    w: 4.23,
    h: 1.4,
    fontSize: 10,
    color: P.dim,
    fontFace: FONT,
    italic: true,
    align,
  });

  return (await pptx.write({ outputType: "nodebuffer" })) as Buffer;
}
