/**
 * Unify the data layer: rewrite src/lib/data/indicators.ts so its MACRO metrics
 * carry the real World Bank seed values (the same data the agent uses) for all
 * 12 countries, while preserving the curated sector/ranking metrics the seed
 * doesn't cover (oil/gas, infra/logistics indexes, competitiveness rank, etc.).
 *
 *   pnpm tsx scripts/sync-mock-from-seed.ts
 *
 * Run after build-seed. Keeps the file static (no runtime fs) so client pages
 * (compare, dashboard, country profile) stay real and consistent.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { COUNTRIES } from "../src/lib/data/countries";
import { readSeedIndicators } from "../src/lib/data/indicator-codes";
import { INDICATORS } from "../src/lib/data/indicators";

// Macro metrics the real seed can fill (old metric name → seed canonical code).
const OLD_TO_SEED: Record<string, string> = {
  gdp_usd_nominal: "gdp",
  gdp_growth_pct: "gdp_growth",
  population: "population",
  co2_per_capita_t: "co2",
  renewables_share_pct: "renew_share",
  exports_usd: "exports",
  fdi_inflows_usd: "fdi",
};
const MACRO_OLD = new Set(Object.keys(OLD_TO_SEED));

interface Seed {
  countryIso3: string;
  metric: string;
  value: number;
  unit: string;
  year: number;
  source: string;
  confidence: "high" | "med" | "low";
}

const merged: Seed[] = [];

for (const country of COUNTRIES) {
  const iso3 = country.iso3;
  const seedRows = readSeedIndicators(iso3);
  const byCode = new Map(seedRows.map((r) => [r.code, r]));

  // 1) Real macro metrics from the seed.
  for (const [oldMetric, seedCode] of Object.entries(OLD_TO_SEED)) {
    const r = byCode.get(seedCode);
    if (!r) continue;
    merged.push({
      countryIso3: iso3,
      metric: oldMetric,
      value: r.value,
      unit: r.unit,
      year: r.year,
      source: "World Bank",
      confidence: "high",
    });
  }

  // 2) Preserve curated sector / ranking metrics the seed doesn't cover.
  for (const old of INDICATORS) {
    if (old.countryIso3 !== iso3 || MACRO_OLD.has(old.metric)) continue;
    merged.push({
      countryIso3: old.countryIso3,
      metric: old.metric,
      value: old.value,
      unit: old.unit,
      year: old.year,
      source: old.source,
      confidence: old.confidence,
    });
  }
}

const body = merged
  .map(
    (s) =>
      `  { countryIso3: ${JSON.stringify(s.countryIso3)}, metric: ${JSON.stringify(s.metric)}, value: ${s.value}, unit: ${JSON.stringify(s.unit)}, year: ${s.year}, source: ${JSON.stringify(s.source)}, confidence: ${JSON.stringify(s.confidence)} },`,
  )
  .join("\n");

const out = `import type { Indicator } from "@/types";

// GENERATED by scripts/sync-mock-from-seed.ts — macro metrics are real World Bank
// values (same source as the agent); sector/ranking metrics are curated. Do not
// hand-edit; re-run \`pnpm tsx scripts/sync-mock-from-seed.ts\` after build-seed.

type IndicatorSeed = Omit<Indicator, "id">;

const seeds: IndicatorSeed[] = [
${body}
];

export const INDICATORS: Indicator[] = seeds.map((s) => ({
  ...s,
  id: \`\${s.countryIso3}-\${s.metric}-\${s.year}\`,
}));

import { liveByCountry, liveFor } from "@/services/ingest/store";

export function indicatorFor(iso3: string, metric: string): Indicator | undefined {
  return (
    liveFor(iso3, metric) ?? INDICATORS.find((i) => i.countryIso3 === iso3 && i.metric === metric)
  );
}

export function indicatorsByCountry(iso3: string): Indicator[] {
  const liveRows = liveByCountry(iso3);
  if (liveRows.length === 0) return INDICATORS.filter((i) => i.countryIso3 === iso3);
  const overlayKeys = new Set(liveRows.map((r) => r.metric));
  const mockKept = INDICATORS.filter((i) => i.countryIso3 === iso3 && !overlayKeys.has(i.metric));
  return [...liveRows, ...mockKept];
}

export function timeSeriesAcrossCountries(metric: string, year: number): Indicator[] {
  return INDICATORS.filter((i) => i.metric === metric && i.year === year);
}
`;

writeFileSync(path.join(process.cwd(), "src", "lib", "data", "indicators.ts"), out);
console.log(
  `Wrote src/lib/data/indicators.ts — ${merged.length} rows (${COUNTRIES.length} countries)`,
);
const macro = merged.filter((s) => MACRO_OLD.has(s.metric)).length;
console.log(`  ${macro} real macro rows · ${merged.length - macro} curated sector rows`);
