/**
 * Fetch Natural Earth 110m land polygons and bake them into an equirectangular
 * SVG path for the dashboard world map. Run once (or when refreshing geometry):
 *
 *   pnpm tsx scripts/build-worldmap.ts
 *
 * Output: src/lib/data/world-map.ts — WORLD_W/H + WORLD_LAND_PATH. Pins are
 * projected with the SAME equirectangular formula so they align with the land.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

const SRC =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";

const W = 1000;
const H = 500;
const px = (lon: number) => ((lon + 180) / 360) * W;
const py = (lat: number) => ((90 - lat) / 180) * H;
const r1 = (n: number) => Math.round(n * 10) / 10;

function ringPath(ring: number[][]): string {
  let d = "";
  ring.forEach(([lon, lat], i) => {
    d += `${i === 0 ? "M" : "L"}${r1(px(lon))} ${r1(py(lat))}`;
  });
  return `${d}Z`;
}

function polyMaxLat(poly: number[][][]): number {
  return Math.max(...poly[0]!.map(([, lat]) => lat));
}

async function main() {
  console.log(`Fetching ${SRC}`);
  const res = await fetch(SRC, { signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
  const geo = (await res.json()) as {
    features: { geometry: { type: string; coordinates: unknown } }[];
  };

  const paths: string[] = [];
  let dropped = 0;
  for (const f of geo.features) {
    const g = f.geometry;
    const polys: number[][][][] =
      g.type === "Polygon"
        ? [g.coordinates as number[][][]]
        : g.type === "MultiPolygon"
          ? (g.coordinates as number[][][][])
          : [];
    for (const poly of polys) {
      // Drop Antarctica (and tiny sub-Antarctic specks) — empty visual mass.
      if (polyMaxLat(poly) < -55) {
        dropped++;
        continue;
      }
      for (const ring of poly) paths.push(ringPath(ring));
    }
  }

  const d = paths.join("");
  const out = `// GENERATED by scripts/build-worldmap.ts — Natural Earth 110m land,
// equirectangular projection. Do not hand-edit.

export const WORLD_W = ${W};
export const WORLD_H = ${H};
export const WORLD_LAND_PATH =
  ${JSON.stringify(d)};
`;
  const dest = path.join(process.cwd(), "src", "lib", "data", "world-map.ts");
  writeFileSync(dest, out);
  console.log(
    `Wrote ${dest} — ${paths.length} rings, ${(d.length / 1024).toFixed(1)}KB path (dropped ${dropped} polar polys)`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
